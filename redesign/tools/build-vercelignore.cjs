// Writes .vercelignore so the Vercel deploy ships only the files the live pages load:
// the new site (index.html, css/, js/) and the archived previous site (old/). Nothing is deleted; it all stays in git.
// Usage (from the project root): node redesign/tools/build-vercelignore.cjs
const fs = require('fs');
const path = require('path');
const root = process.cwd();

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true })
  .flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));
const pageFiles = ['index.html', 'css/styles.css', ...walk('js'), ...walk('old')]
  .map((f) => f.replace(/\\/g, '/'))
  .filter((f) => /\.(html|css|js)$/.test(f));
// block comments are skipped: they mention file names that are never loaded
const text = pageFiles.map((f) => fs.readFileSync(path.join(root, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')).join('\n');

// Every Assets/ path the pages mention (inside quotes, url() or backticks; file names may contain spaces)
const used = new Set();
for (const m of text.matchAll(/(?:\.\.\/|\/)?Assets\/([^"'`)?#]+?\.(?:png|jpe?g|webp|svg|mp4|gif|avif))/gi)) used.add('Assets/' + decodeURI(m[1]));
const missing = [...used].filter((f) => !fs.existsSync(path.join(root, f)));
if (missing.length) { console.error('Referenced but missing:', missing); process.exit(1); }

const unused = walk('Assets').map((f) => f.replace(/\\/g, '/')).filter((f) => !used.has(f)).sort();
const lines = [
  '# Production deploy (Vercel): ship only what the live pages load (the new site at /, the previous site at /old).',
  '# Generated by redesign/tools/build-vercelignore.cjs; re-run it after adding or removing images, videos or pages.',
  '# Nothing listed here is deleted; it all stays in git.',
  '',
  '# Docs, audit, tests and tooling',
  '/redesign/', '/ux-audit/', '/test/', '/.agents/', '/skills-lock.json', '/DESIGN.md',
  '',
  '# Asset files no live page uses',
  ...unused.map((f) => '/' + f),
  '',
];
fs.writeFileSync(path.join(root, '.vercelignore'), lines.join('\n'));
const size = (list) => list.reduce((s, f) => s + fs.statSync(path.join(root, f)).size, 0) / 1048576;
console.log(`pages scanned: ${pageFiles.length} | assets used: ${used.size} (${size([...used]).toFixed(1)} MB) | excluded: ${unused.length} (${size(unused).toFixed(1)} MB)`);
